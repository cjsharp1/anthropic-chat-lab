/**
 * usage.ts — turns the API's token counts into something a learner can read.
 *
 * Every Claude response carries a `usage` object. Logging it raw works, but
 * it puts five similarly-named numbers on screen with no indication of which
 * matter or what they cost. This module names them, totals them, and prices
 * them.
 *
 * It is a separate module because from phase 8 every orchestration pattern
 * needs the same summary, and a pattern that makes five calls needs to add
 * five of them together.
 */

import type Anthropic from "@anthropic-ai/sdk";

/**
 * Published prices in US dollars per million tokens.
 *
 * These are hard-coded and will go out of date. They are here so the cost
 * of a conversation is visible while you learn, not for billing — check
 * the current rates at https://www.anthropic.com/pricing
 *
 * Cached input is much cheaper than fresh input, which is the entire point
 * of prompt caching in step 58. Having both numbers here is what makes that
 * saving visible when it arrives.
 */
const PRICING: Record<string, { input: number; output: number; cacheRead: number }> = {
  "claude-opus-5-5": { input: 4, output: 20, cacheRead: 0.2 },
  "claude-sonnet-5-5": { input: 2, output: 10, cacheRead: 0.2 },
  "claude-haiku-5-5": { input: 0.1, output: 0.5, cacheRead: 0.01 },
};

/** A flattened, named view of one response's token usage. */
export interface UsageSummary {
  /** Fresh input tokens — the prompt, billed at full rate. */
  input: number;
  /** Tokens generated by the model. Always the most expensive line. */
  output: number;
  /** Input served from the cache, at a large discount. Zero until step 58. */
  cacheRead: number;
  /** Tokens written into the cache. Costs slightly more than fresh input. */
  cacheWrite: number;
  /** Every input token, however it was billed. */
  totalInput: number;
  /** Estimated cost in US dollars. */
  cost: number;
  /** What proportion of input came from the cache, 0 to 1. */
  cacheHitRate: number;
}

/**
 * Reads the usage block from a response and prices it.
 *
 * The cache fields are optional in the API type — they are absent on a
 * response that used no caching — so each is defaulted to zero rather than
 * assumed present.
 */
export function summariseUsage(
  usage: Anthropic.Usage,
  model: string,
): UsageSummary {
  const input = usage.input_tokens;
  const output = usage.output_tokens;
  const cacheRead = usage.cache_read_input_tokens ?? 0;
  const cacheWrite = usage.cache_creation_input_tokens ?? 0;

  const totalInput = input + cacheRead + cacheWrite;

  // Fall back to Opus pricing for an unknown model, so the number is
  // indicative rather than zero — silently reporting $0.00 would be worse
  // than being slightly wrong.
  const rates = PRICING[model] ?? PRICING["claude-opus-5-5"]!;

  const cost =
    (input / 1_000_000) * rates.input +
    (output / 1_000_000) * rates.output +
    (cacheRead / 1_000_000) * rates.cacheRead +
    // Writing to the cache costs 25% more than fresh input.
    (cacheWrite / 1_000_000) * rates.input * 1.25;

  return {
    input,
    output,
    cacheRead,
    cacheWrite,
    totalInput,
    cost,
    cacheHitRate: totalInput === 0 ? 0 : cacheRead / totalInput,
  };
}

/**
 * Formats a cost for display.
 *
 * A single turn can cost a fraction of a cent, and "$0.00" tells a learner
 * nothing. Below one cent, show four decimal places.
 */
export function formatCost(dollars: number): string {
  // Four decimals below a dollar, not just below a cent.
  //
  // Two decimals collapse $0.0199 and $0.0250 into the same "$0.02",
  // which is useless for the comparison this app exists to support:
  // every figure here lives between a tenth of a cent and a few
  // cents, and rounding away the difference removes the signal.
  if (dollars === 0) return "$0.00";
  return dollars < 1 ? `$${dollars.toFixed(4)}` : `$${dollars.toFixed(2)}`;
}

/**
 * A short, single-line preview of a reply, for a log row's label.
 *
 * Exists because a response row labelled only with token counts and a
 * cost says nothing about what came back. A reader then expands the
 * JSON and their eye lands on whatever prose is nearest the top —
 * which, when the question was "what does stop_reason max_tokens
 * mean?", is Claude's answer describing a truncated response. The row
 * reads as an error report about itself.
 *
 * Putting a few words of the actual reply in the label removes the
 * ambiguity before anyone expands anything.
 */
export function snippet(text: string, max = 40): string {
  const oneLine = text.replace(/\s+/g, " ").trim();
  if (!oneLine) return "(no text)";
  return oneLine.length <= max ? `"${oneLine}"` : `"${oneLine.slice(0, max)}…"`;
}

/**
 * A running total of what caching has saved across a session.
 *
 * A per-request hit rate bounces around — 96%, then 73%, then 80% —
 * because each request is a different mix of cached prefix and fresh
 * question. That tells you nothing about whether caching is working
 * overall, which is the question a learner actually has.
 *
 * The cumulative figure answers it: across everything sent so far,
 * what share came from cache, and what would the same tokens have
 * cost without it.
 */
export class CacheTally {
  private fresh = 0;
  private read = 0;
  private written = 0;
  private billed = 0;
  private wouldHaveBilled = 0;

  /** Adds one response's usage to the running total. */
  add(usage: UsageSummary, model: string): void {
    const rates = pricingFor(model);

    this.fresh += usage.input;
    this.read += usage.cacheRead;
    this.written += usage.cacheWrite;

    // What was actually charged for input on this request.
    this.billed +=
      (usage.input / 1_000_000) * rates.input +
      (usage.cacheRead / 1_000_000) * rates.cacheRead +
      (usage.cacheWrite / 1_000_000) * rates.input * 1.25;

    // What the same tokens would have cost with no caching at all:
    // every one of them billed as fresh input.
    this.wouldHaveBilled +=
      ((usage.input + usage.cacheRead + usage.cacheWrite) / 1_000_000) *
      rates.input;
  }

  /** The figures, for the log. */
  summary(): {
    totalInput: number;
    fromCache: number;
    hitRate: number;
    inputCost: number;
    withoutCaching: number;
    saved: number;
    savedPercent: number;
  } {
    const totalInput = this.fresh + this.read + this.written;

    return {
      totalInput,
      fromCache: this.read,
      hitRate: totalInput === 0 ? 0 : this.read / totalInput,
      inputCost: this.billed,
      withoutCaching: this.wouldHaveBilled,
      saved: this.wouldHaveBilled - this.billed,
      savedPercent:
        this.wouldHaveBilled === 0
          ? 0
          : (this.wouldHaveBilled - this.billed) / this.wouldHaveBilled,
    };
  }
}

/** The published rates for a model, falling back to Opus. */
function pricingFor(model: string): {
  input: number;
  output: number;
  cacheRead: number;
} {
  return PRICING[model] ?? PRICING["claude-opus-5-5"]!;
}
